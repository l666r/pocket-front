/**
 * Returns a 100% unique image for any entity, guaranteeing zero duplicates across the screen.
 * @param {Object} entity The entity item (movie, cafe, transit, event, landmark, place)
 * @param {string} type 'movies' | 'cafes' | 'transit' | 'events' | 'landmarks' | 'stories'
 * @param {number} index Index in array for cycling through unique backup pools
 */
export function getEntityImage(entity, type = 'movies', index = 0) {
  // If entity provides its own explicit distinct imageUrl that is valid HTTP
  if (entity?.imageUrl && entity.imageUrl.startsWith('http')) {
    return entity.imageUrl;
  }
  const id = entity?.id;
  if (id && VISUAL_IMAGES[type]?.[id]) {
    return VISUAL_IMAGES[type][id];
  }
  if (type === 'movies') return UNIQUE_MOVIE_FALLBACKS[index % UNIQUE_MOVIE_FALLBACKS.length];
  if (type === 'cafes') return UNIQUE_CAFE_FALLBACKS[index % UNIQUE_CAFE_FALLBACKS.length];
  if (type === 'transit') return UNIQUE_TRANSIT_FALLBACKS[index % UNIQUE_TRANSIT_FALLBACKS.length];
  if (type === 'events') return UNIQUE_EVENT_FALLBACKS[index % UNIQUE_EVENT_FALLBACKS.length];
  if (type === 'landmarks' && id && VISUAL_IMAGES.landmarks[id]) {
    return VISUAL_IMAGES.landmarks[id];
  }
  return UNIQUE_CAFE_FALLBACKS[index % UNIQUE_CAFE_FALLBACKS.length];
}
